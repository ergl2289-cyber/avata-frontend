let junctionId = 1
/** Build cars.files junction rows from a list of photo URLs (Directus shape). */
function files(...urls: string[]): CarFileJunction[] {
  return urls.map((url) => {
    const file: DirectusFile = { id: url, filename_download: 'car.jpg' }
    return { id: junctionId++, directus_files_id: file }
  })
}

